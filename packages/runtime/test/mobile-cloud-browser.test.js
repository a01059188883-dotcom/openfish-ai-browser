import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

test("mobile frontend is served by the Worker and uses authenticated cloud browser routes", async () => {
  const worker = await readFile(resolve("cloudflare/worker.js"), "utf8");
  const config = await readFile(resolve("cloudflare/wrangler.toml"), "utf8");
  const html = await readFile(resolve("public/index.html"), "utf8");
  const app = await readFile(resolve("public/app.js"), "utf8");
  const admin = await readFile(resolve("cloudflare/mobile-admin.html"), "utf8");
  assert.ok(config.includes('[browser]'));
  assert.ok(config.includes('binding = "BROWSER"'));
  assert.ok(config.includes('"nodejs_compat"'));
  assert.ok(config.includes('[assets]'));
  assert.ok(worker.includes('import { acquire, connect } from "@cloudflare/playwright"'));
  assert.ok(worker.includes('url.pathname.startsWith("/api/cloud-browser/")'));
  for (const route of ["/api/cloud-browser/download", "/api/cloud-browser/downloads", "/api/cloud-browser/downloads/remove"]) assert.ok(worker.includes(route));
  assert.ok(worker.includes('"/cloud/downloads"'));
  assert.ok(worker.includes('"/cloud/download"'));
  assert.ok(worker.includes('const storageKey = key => "cloudBrowser:" + sessionId + ":" + key'));
  assert.ok(worker.includes('withCloudSessionLock'));
  assert.ok(worker.includes('cloudBrowserLastUsedAt'));
  assert.ok(worker.includes('cloudLocks = new Map()'));
  assert.ok(worker.includes('"x-openfish-session": request.headers.get("x-openfish-session") || ""'));
  assert.ok(worker.includes('access-control-allow-headers": "Authorization, Content-Type, X-OpenFish-Session"'));
  assert.ok(app.includes('SESSION_KEY="openfish.browser.session"'));
  assert.ok(app.includes('"X-OpenFish-Session":sessionId'));
  assert.ok(admin.includes('ADMIN_SESSION_KEY="openfish.admin.browser.session"'));

  assert.ok(worker.includes('const storageKey = key => "cloudBrowser:" + sessionId + ":" + key'));
  assert.ok(worker.includes('"x-openfish-session": sessionId'));
  assert.ok(app.includes('"X-OpenFish-Session":sessionId'));
  assert.ok(app.includes('SESSION_KEY="openfish.browser.session"'));
  assert.ok(worker.includes('const readOnlyRoute = ["/api/cloud-browser/status", "/api/cloud-browser/view", "/api/cloud-browser/tabs", "/api/cloud-browser/downloads"].includes(url.pathname)'));
  assert.ok(worker.includes('if (readOnlyRoute && request.method !== "GET")'));
  assert.ok(worker.includes('if (!readOnlyRoute && request.method !== "POST")'));
  assert.ok(worker.includes('/api/v1/browser/navigate'));
  assert.ok(worker.includes('/api/v1/browser/action'));
  assert.ok(worker.includes('/api/v1/browser/tabs'));
  assert.ok(worker.includes('url.pathname === "/cloud/tabs"'));
  assert.ok(worker.includes('/api/v1/openapi.json'));
  assert.ok(worker.includes('access-control-allow-origin'));
  assert.ok(worker.includes('const VERSION = "2.13.3"'));
  assert.ok(worker.includes('if (!authorized(request, env))'));
  assert.ok(worker.includes('acquire(this.env.BROWSER)'));
  assert.ok(worker.includes('connect(this.env.BROWSER, acquired.sessionId)'));
  assert.ok(worker.includes('page.setViewportSize({ width: 1280, height: 820 })'));
  assert.ok(worker.includes('connect(this.env.BROWSER, stored)'));
  assert.ok(worker.includes('browser.contexts().flatMap(context => context.pages())'));
  assert.ok(worker.includes('await browser.close()'));
  assert.ok(!worker.includes("puppeteer."));
  assert.ok(worker.includes('validateTarget'));
  assert.ok(worker.includes('context.route("**/*"'));
  assert.ok(worker.includes('context.routeWebSocket'));
  assert.ok(worker.includes('browser.disconnect()'));
  assert.ok(worker.includes('guardedBrowserContexts'));
  for (const id of ["url", "back", "forward", "reload", "go", "viewport", "sendText", "bookmark", "bookmarks", "tabs", "addTab"]) assert.ok(html.includes('id="' + id + '"'));
  for (const route of ["/api/cloud-browser/status", "/api/cloud-browser/view", "/api/cloud-browser/tabs", "/api/cloud-browser/navigate", "/api/cloud-browser/action", "/api/cloud-browser/close"]) assert.ok(worker.includes(route));
  assert.ok(app.includes("data:image/jpeg;base64,"));
  assert.ok(app.includes("(event.clientY-rect.top)/rect.height*820"));
  assert.ok(app.includes("/api/cloud-browser/navigate"));
  assert.ok(app.includes("/api/cloud-browser/action"));
  assert.ok(app.includes('act("newTab")'));
  assert.ok(app.includes('act("switchTab"'));
  assert.ok(app.includes('act("closeTab"'));
  assert.ok(app.includes("function renderTabs"));
  assert.ok(admin.includes('id="cloudStatus"'));
  assert.ok(admin.includes('id="cloudClose"'));
  assert.ok(admin.includes('sessionStorage.setItem("openfish.relay.token"'));
  assert.ok(admin.includes('api("/api/cloud-browser/status")'));
});
